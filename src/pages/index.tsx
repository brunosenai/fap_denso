import Head from "next/head";
import Image from "next/image";
import styles from "@/styles/Index.module.css";
import { useRouter } from "next/router";
import { useEffect } from "react";

export default function Index() {
  const router=useRouter()
 
  useEffect(() => {
    const checkDeviceAndRedirect = () => {
      const userAgent = navigator.userAgent.toLowerCase();
      const isTablet = /(ipad|tablet|(android(?!.*mobile))|(windows(?!.*phone)(.*touch))|kindle|playbook|silk|(puffin(?!.*(IP|AP|WP))))/.test(userAgent);
      localStorage.setItem('isTablet',isTablet.toString())
      router.push('/login'); 
    };
    checkDeviceAndRedirect();
  }, [router]);

  return (
    <>
      <Head>
        <title>Denso - Teste de Aptidão Prática</title>
        <meta name="description" content="Generated by create next app" />
        <meta name="viewport" content="width=device-width, initial-scale=1" />
        <link rel="icon" href="/assets/icons/favicon.ico?v=2" />
      </Head>
      <div className='page'>
        <main className='main'>
            <Image src="/assets/icons/person.png" alt="Email" width={51} height={51} />
        </main>
      </div>
    </>
  );
}
