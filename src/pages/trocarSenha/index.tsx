import Head from "next/head";
import styles from "@/styles/TrocarSenha.module.css";
import { useRouter } from "next/router";
import { useState, useEffect } from "react";

export default function TrocarSenha() {
  const router=useRouter()
  const [email,setEmail]=useState('')
  const [senhaAtual,setSenhaAtual]=useState('')
  const [novaSenha1,setNovaSenha1]=useState('')
  const [novaSenha2,setNovaSenha2]=useState('')

  useEffect(()=>{
    const getemail=router.query.email as string
    setEmail(getemail)
  },[])

  const goto=(path:string)=>{
    router.push(path)
  }

  const validarEmailAtual=async()=>{
    const endpoint=`api/apiLogin?email=${email}&action=validarEmailAtual`
    const response=await fetch(endpoint)
    if(response.status!=200){
        return false
    }
    return true
  }

  const validarSenhaAtual=async()=>{
    const endpoint=`/api/apiLogin`
    const response=await fetch(endpoint, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        action:'validarSenha',
        email: `${email}`,
        password: `${senhaAtual}`
      }),
    })
    if(response.status!=200){
        return false
    }
    return true
  }

  const compararSenhas=()=>{
    if(novaSenha1!=novaSenha2){
        alert('As novas senhas não coincidem, por favor verifique e tente novamente!')
        return false
    }
    return true
  }

  const trocarSenha=async()=>{
    if(senhaAtual==''){
        alert('Preencha o campo Senha Atual para trocar a senha!')
        return
    }else if(novaSenha1==''){
        alert('Preencha o campo Nova Senha para trocar a senha!')
        return
    }else if(novaSenha2==''){
        alert('Preencha o campo Redigite a Nova Senha para trocar a senha!')
        return
    }

    if(!await validarEmailAtual()){
        alert('O E-Mail atual informada está incorreto!')
        return
    }

    if(!await validarSenhaAtual()){
        alert('A senha atual informada está incorreta!')
        return
    }

    if(!compararSenhas()){
        return
    }

    const endpoint=`/api/apiLogin`
    fetch(endpoint, {
      method: 'PUT',
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        action:'trocarSenha',
        email: `${email}`,
        password: `${novaSenha1}`
      }),
    }).then((response)=>{
      if(response.status==200){
        alert('Senha alterada com sucesso!')
      }else{
        alert('Ocorreu um erro ao trocar a senha, tente novamente mais tarde!')
      }
    }).catch((error)=>{
      console.error('Error:', error);
      alert('Ocorreu um erro ao trocar a senha, tente novamente mais tarde!')
    })
  }

  return (
    <>
      <Head>
        <title>Stellantis - Teste de Aptidão Prática</title>
        <meta name="description" content="Generated by create next app" />
        <meta name="viewport" content="width=device-width, initial-scale=1" />
        <link rel="icon" href="/favicon.ico" />
      </Head>
      <div className='page'>
        <main className='main'>
          <div className={styles.trocarSenha}>
            <h1>Troca de Senha</h1>
            <div className={styles.inputField}>
                <label>E-Mail</label>
                <input type="text" value={email} onChange={(e)=>setEmail(e.target.value)} placeholder="Email para receber a nova senha" readOnly/>
            </div>
            <div className={styles.inputField}>
                <label>Senha Atual</label>
                <input type="password" value={senhaAtual} onChange={(e)=>setSenhaAtual(e.target.value)} placeholder="Senha atual" />
            </div>
            <div className={styles.inputField}>
                <label>Nova Senha</label>
                <input type="password" value={novaSenha1} onChange={(e)=>setNovaSenha1(e.target.value)} placeholder="Nova Senha" />
            </div>   
            <div className={styles.inputField}>
                <label>Redigite a Nova Senha</label>
                <input type="password" value={novaSenha2} onChange={(e)=>setNovaSenha2(e.target.value)} placeholder="Redigite a Nova Senha" />
            </div>
            <div className={styles.inputField_c}>
                <button className='btnPadrao_claro' onClick={()=>router.push('/')}>voltar</button>
                <button className='btnPadrao_claro' onClick={trocarSenha}>Trocar Senha</button>
            </div>                 
          </div>
        </main>
      </div>
    </>
  );
}
