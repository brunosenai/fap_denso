import Head from "next/head";
import styles from "@/styles/EsqueciSenha.module.css";
import { useRouter } from "next/router";
import Load from "@/components/Load/Load";
import Image from "next/image";
import { useState, useEffect } from "react";

export default function EsqueciSenha() {
const router=useRouter()
const [email,setEmail]=useState('')
const [codigoRedefinicao,setCodigoRedefinicao]=useState('')
const [novaSenha1,setNovaSenha1]=useState('')
const [novaSenha2,setNovaSenha2]=useState('')
const [passo,setPasso]=useState(0)
const [load,setLoad]=useState(false)
const [tipoCampoSenha_s1,setTipoCampoSenha_s1]=useState('password')
const [tipoCampoSenha_s2,setTipoCampoSenha_s2]=useState('password')

useEffect(()=>{
    const getemail=router.query.email as string
    setEmail(getemail)
},[])

const enviarCodigoRederinicao=()=>{
    setLoad(true)
    const endpoint=`/api/apiLogin`
    fetch(endpoint, {
    method: 'POST',
    headers: {
        'Content-Type': 'application/json',
    },
    body: JSON.stringify({
        action:'enviarCodigoRedefinicao',
        email: `${email}`,
        apiKey: process.env.NEXT_PUBLIC_API_KEY
    }),
    }).then((response)=>{
        setLoad(false)
        if(response.status==200){
            setPasso(1)
        }else{
            alert('Ocorreu um erro ao enviar o código de redefinição, tente novamente mais tarde!')
        }
    }).catch((error)=>{
        setLoad(false)
        console.error('Error:', error);
        alert('Ocorreu um erro ao enviar o código de redefinição, tente novamente mais tarde!')
    }).finally(()=>{
        setLoad(false)
    });
}

const validarCodigoRederinicao=()=>{
    setLoad(true)
    const endpoint=`/api/apiLogin`
    fetch(endpoint, {
    method: 'POST',
    headers: {
        'Content-Type': 'application/json',
    },
    body: JSON.stringify({
        action:'validarCodigo',
        email: `${email}`,
        codigo:`${codigoRedefinicao}`,
        apiKey: process.env.NEXT_PUBLIC_API_KEY
    }),
    }).then((response)=>{
        setLoad(false)
        if(response.status==200){
            setPasso(2)
        }else{
            alert('Código de redefinição inválido!')
        }
    }).catch((error)=>{
        setLoad(false)
        console.error('Error:', error);
        alert('Erro ao validar código de redefinição')
    }).finally(()=>{
        setLoad(false)
    });
}

const redefinirSenha=()=>{
    setLoad(true)
    const endpoint=`/api/apiLogin`
    fetch(endpoint, {
    method: 'PUT',
    headers: {
        'Content-Type': 'application/json',
    },
    body: JSON.stringify({
        action:'redefinirSenha',
        email: email,
        password:novaSenha1,
        apiKey: process.env.NEXT_PUBLIC_API_KEY
    }),
    }).then((response)=>{
        setLoad(false)
        if(response.status==200){
            alert('Senha redefinida com sucesso!')
            router.replace('/')
        }else{
            alert('Erro ao redefinir senha!')
        }
    }).catch((error)=>{
        setLoad(false)
        console.error('Error:', error);
        alert('Erro ao redefinir senha!')
    }).finally(()=>{
        setLoad(false)
    });
}

const mudarTipoCampoSenha_s1=()=>{
    if(tipoCampoSenha_s1=='password'){
      setTipoCampoSenha_s1('text')
    }else{
      setTipoCampoSenha_s1('password')
    }
}

const mudarTipoCampoSenha_s2=()=>{
    if(tipoCampoSenha_s2=='password'){
      setTipoCampoSenha_s2('text')
    }else{
      setTipoCampoSenha_s2('password')
    }
}

return (
    <>
        {load&&<Load/>}
        <Head>
            <title>Stellantis - Teste de Aptidão Prática</title>
            <meta name="description" content="Generated by create next app" />
            <meta name="viewport" content="width=device-width, initial-scale=1" />
            <link rel="icon" href="/assets/icons/favicon.ico?v=2" />
        </Head>
        <div className='page'>
            <main className={styles.main}>
                <div className={styles.esqueciSenha}>
                    <h1>Recuperar Senha</h1>
                    <div className={styles.inputField}>
                        <label>E-Mail</label>
                        <input type="text" value={email} onChange={(e)=>setEmail(e.target.value)} placeholder="Email para receber a nova senha" readOnly/>
                    </div>
                    <div className={styles.inputField_c}>
                        <button className='btnPadrao_claro' onClick={enviarCodigoRederinicao}>{passo>0?'Reenviar Código de redefinição':'Enviar Código de redefinição'}</button>
                    </div> 

                    <div className={`${styles.areaField} ${passo==1&&styles.areaField_show}`}>
                        <div className={styles.inputField}>
                            <label>Código de Recuperação</label>
                            <input type="text" value={codigoRedefinicao} onChange={(e)=>setCodigoRedefinicao(e.target.value)} placeholder="Código de recuperação" />
                        </div>
                        <div className={styles.inputField_c}>
                            <button className='btnPadrao_claro' onClick={validarCodigoRederinicao}>Validar Código</button>
                        </div> 
                    </div>

                    <div className={`${styles.areaField} ${passo==2&&styles.areaField_show}`}>
                        <div className={styles.inputField}>
                            <label>Nova Senha</label>
                            <div className={styles.fieldSenha}>
                                <input type={tipoCampoSenha_s1=='password'?'password':'text'} value={novaSenha1} onChange={(e)=>setNovaSenha1(e.target.value)} placeholder="Nova Senha" />
                                <Image src={tipoCampoSenha_s1=='password'?'/assets/icons/visibility_off_b.svg':'/assets/icons/visibility_on_b.svg'} alt="Mostrar Senha" width={35} height={35} onClick={mudarTipoCampoSenha_s1}/>
                            </div>
                        </div>
                        <div className={styles.inputField}>
                            <label>Redigite a Nova Senha</label>
                            <div className={styles.fieldSenha}>
                                <input type={tipoCampoSenha_s2=='password'?'password':'text'} value={novaSenha2} onChange={(e)=>setNovaSenha2(e.target.value)} placeholder="Redigite a Nova Senha" />
                                <Image src={tipoCampoSenha_s2=='password'?'/assets/icons/visibility_off_b.svg':'/assets/icons/visibility_on_b.svg'} alt="Mostrar Senha" width={35} height={35} onClick={mudarTipoCampoSenha_s2}/>
                            </div>
                        </div>                        
                        <div className={styles.inputField_c}>
                            <button className='btnPadrao_claro' onClick={redefinirSenha}>Redefinir Senha</button>
                        </div>                     
                    </div>

                </div>
                <div className={styles.rodape}>
                    <button className='btnPadrao_claro' onClick={()=>router.push('/')}>voltar</button>
                </div>                 
            </main>
        </div>
    </>
);
}
